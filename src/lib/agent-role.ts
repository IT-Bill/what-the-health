export type AgentRole = (typeof AGENT_ROLES)[number]["id"];

export const DEFAULT_AGENT_ROLE: AgentRole = "companion";

export function isValidAgentRole(role: string): role is AgentRole {
  return AGENT_ROLES.some((r) => r.id === role);
}

